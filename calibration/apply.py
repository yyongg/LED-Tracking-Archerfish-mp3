"""Write a calibration run into calibration_values.h in each sketch.

    python calibration/apply.py [--run 20261009_104859]   (default: latest run)
"""

import argparse
import re
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent / "data"
REPO = Path(__file__).resolve().parent.parent
SKETCH_DIRS = [REPO / "tracking_mechanism", REPO / "tests" / "mechanism_test"]


def apply(stamp):
    text = (DATA_DIR / f"{stamp}_constants.txt").read_text()
    offsets, gains = re.findall(r"^const float .*;$", text, re.M)
    min_brightness = re.search(r"MIN_BRIGHTNESS = (\d+)", text).group(1)
    found_threshold = re.search(r"FOUND_THRESHOLD = ([\d.]+)", text).group(1)

    header = "\n".join([
        f"// Generated by calibration/apply.py from calibration run {stamp}. Do not edit by hand:",
        "// rerun calibrate.py (or apply.py) instead. Calibrated reading = (raw - OFF) * GAIN.",
        "#pragma once",
        "",
        offsets,
        gains,
        "",
        "// minimum summed calibrated reading of all 4 sensors to count as seeing the LED",
        f"const int MIN_BRIGHTNESS = {min_brightness};",
        "",
        "// sensor noise with a still, centered LED; not applied, FOUND_THRESHOLD is set by hand",
        f"const float CAL_SUGGESTED_FOUND_THRESHOLD = {found_threshold};",
        "",
    ])
    for folder in SKETCH_DIRS:
        (folder / "calibration_values.h").write_text(header)
        print(f"wrote {folder.name}/calibration_values.h from run {stamp}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--run")
    args = parser.parse_args()
    latest = sorted(DATA_DIR.glob("*_constants.txt"))[-1].name.removesuffix("_constants.txt")
    apply(args.run or latest)
